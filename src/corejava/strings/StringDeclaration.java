package corejava.strings;

/**
 * Topic: Strings
 * Program: String Declaration
 * Description: Demonstrates the declaration, initialization, and printing of string variables.
 * Author: Siddhesh
 */

public class StringDeclaration {
	
	public static void main(String[] args) {
		
		// Declare and initialize variables
		
		String firstName = "Siddhesh";
		String lastName = "Thakur";
		String city = "Navi Mumbai";

		// Display the results
		
		System.out.println("==============================");
		System.out.println("      STRING DECLARATION      ");
		System.out.println("==============================");
		System.out.println();
		
		System.out.println("First Name : " + firstName);
		System.out.println("Last Name  : " + lastName);
		System.out.println("City       : " + city);
		System.out.println();
		
		System.out.println("==============================");
		
	}

}
